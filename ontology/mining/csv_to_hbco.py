#!/usr/bin/env python3
"""
csv_to_hbco.py — Convert concept_terms_raw.csv -> ontology/hbco_mappings.ttl

Output is a valid Turtle ABox that instantiates hbco:Concept and
hbco:CompositeConcept individuals from the reviewed vocabulary CSV.

Per-building overlay: if input/<building_id>/concepts.ttl exists it is
loaded on orchestrator start via ttl_uploader.discover_ttls() — document
that path in input/README if concepts are building-specific.

Usage:
    python3 ontology/mining/csv_to_hbco.py
    python3 ontology/mining/csv_to_hbco.py --csv ontology/mining/concept_terms_raw.csv
"""
from __future__ import annotations

import argparse
import csv
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CSV = REPO_ROOT / "ontology" / "mining" / "concept_terms_raw.csv"
DEFAULT_OUT = REPO_ROOT / "ontology" / "hbco_mappings.ttl"

HBCO = "http://ontosage.org/hbco#"
BRICK_NS = "https://brickschema.org/schema/Brick#"


def _ttl_str(value: str) -> str:
    """Escape a string for use inside double-quoted Turtle literal."""
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def build_ttl(rows: list[dict]) -> str:
    # Find which concept_ids are referenced as composite parents
    parent_ids = {r["composite_of"].strip() for r in rows if r.get("composite_of", "").strip()}

    lines: list[str] = []
    lines += [
        "# HBCO ABox — generated by ontology/mining/csv_to_hbco.py",
        "# Source: ontology/mining/concept_terms_raw.csv",
        "# DO NOT EDIT manually — regenerate via csv_to_hbco.py after editing the CSV.",
        "",
        "@prefix rdf:    <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .",
        "@prefix rdfs:   <http://www.w3.org/2000/01/rdf-schema#> .",
        "@prefix owl:    <http://www.w3.org/2002/07/owl#> .",
        "@prefix xsd:    <http://www.w3.org/2001/XMLSchema#> .",
        "@prefix skos:   <http://www.w3.org/2004/02/skos/core#> .",
        "@prefix brick:  <https://brickschema.org/schema/Brick#> .",
        "@prefix hbco:   <http://ontosage.org/hbco#> .",
        # OCBV terms. A concept may map to a class Brick does not have --
        # ontosage:Parking_Occupancy_Sensor exists because brick has no bay-count
        # class -- and without this prefix the generated file simply does not parse.
        "@prefix ontosage: <http://ontosage.org/capabilities#> .",
        "",
    ]

    for r in rows:
        cid = r.get("concept_id", "").strip()
        if not cid:
            continue

        lay_raw = r.get("lay_terms", "").strip()
        brick_raw = r.get("brick_classes", "").strip()
        recipe = r.get("recipe_kind", "").strip()
        composite_of = r.get("composite_of", "").strip()
        confidence = r.get("confidence", "").strip()

        lay_terms = [t.strip() for t in lay_raw.split("|") if t.strip()]
        brick_classes = [b.strip() for b in brick_raw.split("|") if b.strip()]

        # Determine rdf:type
        rdf_type = "hbco:CompositeConcept" if cid in parent_ids else "hbco:Concept"

        uri = f"hbco:{cid}"
        lines.append(f"{uri} rdf:type {rdf_type} ,")
        lines.append(f"               owl:NamedIndividual ;")

        lines.append(f'    hbco:conceptId "{_ttl_str(cid)}"^^xsd:string ;')

        # Label (first lay term as skos:prefLabel)
        if lay_terms:
            lines.append(f'    skos:prefLabel "{_ttl_str(lay_terms[0])}"@en ;')
        for term in lay_terms:
            lines.append(f'    hbco:layTerm "{_ttl_str(term)}"^^xsd:string ;')

        for bc in brick_classes:
            # bc is already prefixed e.g. brick:Temperature_Sensor
            lines.append(f"    hbco:mapsToBrickClass {bc} ;")

        if recipe:
            lines.append(f'    hbco:requiresRecipe "{_ttl_str(recipe)}"^^xsd:string ;')

        if composite_of:
            lines.append(f"    hbco:componentOf hbco:{composite_of} ;")

        if confidence:
            lines.append(f'    hbco:confidence "{_ttl_str(confidence)}"^^xsd:string ;')

        # Close the statement (replace last ';' with '.')
        if lines[-1].endswith(" ;"):
            lines[-1] = lines[-1][:-2] + " ."
        lines.append("")

    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Convert concept CSV to HBCO ABox TTL")
    parser.add_argument("--csv", default=str(DEFAULT_CSV), help="Path to concept_terms_raw.csv")
    parser.add_argument("--out", default=str(DEFAULT_OUT), help="Output TTL path")
    parser.add_argument("--dry-run", action="store_true", help="Print stats only, no file write")
    args = parser.parse_args()

    csv_path = Path(args.csv)
    if not csv_path.exists():
        print(f"ERROR: CSV not found at {csv_path}", file=sys.stderr)
        sys.exit(1)

    with open(csv_path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    print(f"[csv_to_hbco] Read {len(rows)} concept rows from {csv_path}")

    ttl = build_ttl(rows)

    if args.dry_run:
        count = ttl.count("hbco:Concept") + ttl.count("hbco:CompositeConcept")
        print(
            f"[csv_to_hbco] dry-run: would write {len(ttl.splitlines())} lines, ~{count} concept entries"
        )
        return

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(ttl, encoding="utf-8")
    print(f"[csv_to_hbco] Wrote {out_path}")

    # Validate with rdflib
    try:
        import rdflib  # type: ignore

        g = rdflib.Graph()
        g.parse(str(out_path), format="turtle")
        print(f"[csv_to_hbco] rdflib OK: {len(g)} triples")
    except Exception as e:
        print(f"[csv_to_hbco] WARNING: rdflib validation failed: {e}", file=sys.stderr)


if __name__ == "__main__":
    main()
