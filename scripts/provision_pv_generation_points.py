#!/usr/bin/env python3
"""Type the power points of photovoltaic equipment as PV generation sensors (BUG-1580).

"How much power are the solar panels generating right now?" was answered with the floor energy
meters: the PV arrays' power points were typed only `brick:Active_Power_Sensor`, the class every
power point in the building shares, so a solar question could resolve to all of them. The pinned
Brick version has PV equipment classes but no generation point class, so OntoSage declares one
(`ontosage:PV_Generation_Power_Sensor`, a subclass of Active_Power_Sensor, in the shared schema).

Which points are PV generation is read from the live graph: a power point that is part of, or a
point of, equipment typed as PV (PV_Panel, PV_Array, Photovoltaic_Inverter, PV_Generation_System).
Only the extra `rdf:type` triples are written; re-running is idempotent. Building-agnostic: the
classes are Brick/OntoSage vocabulary and the namespace is read from the points.

    python scripts/provision_pv_generation_points.py --building bldg1
    python scripts/provision_pv_generation_points.py --building bldg1 --dry-run
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Dict, List

import requests

QUERY = """
PREFIX rdf:   <http://www.w3.org/1999/02/22-rdf-syntax-ns#>
PREFIX brick: <https://brickschema.org/schema/Brick#>
SELECT DISTINCT ?p ?label WHERE {
  VALUES ?eqcls { brick:PV_Panel brick:PV_Array brick:Photovoltaic_Inverter
                  brick:PV_Generation_System }
  ?eq rdf:type ?eqcls .
  ?p (brick:isPointOf|brick:isPartOf) ?eq ;
     rdf:type brick:Electric_Power_Sensor .
  OPTIONAL { ?p rdfs:label ?label }
}
LIMIT 500
"""

#: The unit a point's OWN label states, "(kW)" or "[kW]", as a QUDT unit. The points carried no
#: unit triple, so the pipeline took the unit of the store they sit in (kWh, an energy meter
#: table) and narrated a power reading as energy. Only a unit the label states is written.
_LABEL_UNIT = re.compile(r"[\[(]\s*(kW|W|MW)\s*[\])]")
_QUDT = {"kW": "KiloW", "W": "W", "MW": "MegaW"}


def fetch(endpoint: str) -> Dict[str, str]:
    r = requests.post(
        endpoint,
        data={"query": "PREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#>\n" + QUERY},
        headers={"Accept": "application/sparql-results+json"},
        timeout=60,
    )
    r.raise_for_status()
    out: Dict[str, str] = {}
    for b in r.json()["results"]["bindings"]:
        out.setdefault(b["p"]["value"], (b.get("label") or {}).get("value", ""))
    return out


def build_ttl(labelled: Dict[str, str]) -> str:
    points = sorted(labelled)
    spaces = {p.rsplit("#", 1)[0] for p in points if "#" in p}
    ns = next(iter(spaces)) if len(spaces) == 1 else ""
    lines = [
        "# Power points of photovoltaic equipment, typed as PV generation sensors (BUG-1580).",
        "#",
        "# GENERATED by scripts/provision_pv_generation_points.py from the live graph: a power",
        "# point that is part of PV equipment. Extra rdf:type triples only.",
        "",
        "@prefix rdf:      <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .",
        "@prefix ontosage: <http://ontosage.org/capabilities#> .",
        "@prefix qudt:     <http://qudt.org/schema/qudt/> .",
    ]
    if ns:
        lines.append(f"@prefix bldg:     <{ns}#> .")
    lines.append("")
    for p in points:
        name = f"bldg:{p.rsplit('#', 1)[1]}" if ns else f"<{p}>"
        m = _LABEL_UNIT.search(labelled.get(p) or "")
        if m:
            lines.append(f"{name} rdf:type ontosage:PV_Generation_Power_Sensor ;")
            lines.append(f"    qudt:hasUnit <http://qudt.org/vocab/unit/{_QUDT[m.group(1)]}> .")
        else:
            lines.append(f"{name} rdf:type ontosage:PV_Generation_Power_Sensor .")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--building", required=True)
    ap.add_argument("--endpoint", default="http://127.0.0.1:7200/repositories/bldg")
    ap.add_argument("--out", default="")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    points = fetch(args.endpoint)
    ttl = build_ttl(points)
    if args.dry_run:
        print(ttl)
        return 0
    out = (
        Path(args.out) if args.out else Path("input") / f"{args.building}_pv_generation_points.ttl"
    )
    out.write_text(ttl, encoding="utf-8")
    print(f"wrote {len(points)} PV generation point(s) to {out}")
    return 0 if points else 1


if __name__ == "__main__":
    sys.exit(main())
