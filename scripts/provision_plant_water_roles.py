#!/usr/bin/env python3
"""Type each plant water-temperature point by the circuit it measures (BUG-1564).

"What's the chilled water supply temperature right now?" was answered "I don't have a reading for
chilled water supply temperature" while the chiller's leaving-water point was live. The point was
typed only `brick:Leaving_Water_Temperature_Sensor`, which says "water leaving some equipment" and
not which circuit: an operator says "chilled water supply" or "LTHW flow", and Brick has a class
for each of those (`Leaving_Chilled_Water_Temperature_Sensor`, `Leaving_Hot_Water_Temperature_
Sensor`, and the two `Entering_` returns).

The circuit follows from the equipment the point belongs to, which the graph already states: a
chiller's water is chilled water; a boiler's or a heating heat pump's is hot water. This script
reads that from the live graph and writes ONLY the extra `rdf:type` triples, so it never touches
the generated point files and a re-run is idempotent. Building-agnostic: the equipment classes and
the role classes are Brick vocabulary, the namespace is read from the points themselves.

    python scripts/provision_plant_water_roles.py --building bldg1            # writes the TTL
    python scripts/provision_plant_water_roles.py --building bldg1 --dry-run  # prints it
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Dict, List, Tuple

import requests

#: (direction class, equipment kind) -> the Brick class naming the circuit. A heat pump is typed
#: for HEATING because that is how this estate's provisioning generated its series (flow hotter
#: than return); a building whose heat pump chills would declare its points directly.
ROLE: Dict[Tuple[str, str], str] = {
    ("Leaving_Water_Temperature_Sensor", "chiller"): "Leaving_Chilled_Water_Temperature_Sensor",
    ("Entering_Water_Temperature_Sensor", "chiller"): "Entering_Chilled_Water_Temperature_Sensor",
    ("Leaving_Water_Temperature_Sensor", "heating"): "Leaving_Hot_Water_Temperature_Sensor",
    ("Entering_Water_Temperature_Sensor", "heating"): "Entering_Hot_Water_Temperature_Sensor",
}

QUERY = """
PREFIX rdf:   <http://www.w3.org/1999/02/22-rdf-syntax-ns#>
PREFIX brick: <https://brickschema.org/schema/Brick#>
SELECT DISTINCT ?p ?dir ?eqcls WHERE {
  VALUES ?dir { brick:Leaving_Water_Temperature_Sensor brick:Entering_Water_Temperature_Sensor }
  ?p rdf:type ?dir ; brick:isPointOf ?eq .
  ?eq rdf:type ?eqcls .
  FILTER(REGEX(STR(?eqcls), "(Chiller|Boiler|Heat_Pump)$"))
}
LIMIT 2000
"""


def kind_of(eq_class: str) -> str:
    return "chiller" if eq_class.endswith("Chiller") else "heating"


def fetch(endpoint: str) -> List[Tuple[str, str, str]]:
    r = requests.post(
        endpoint,
        data={"query": QUERY},
        headers={"Accept": "application/sparql-results+json"},
        timeout=60,
    )
    r.raise_for_status()
    out = []
    for b in r.json()["results"]["bindings"]:
        out.append((b["p"]["value"], b["dir"]["value"], b["eqcls"]["value"]))
    return out


def build_ttl(rows: List[Tuple[str, str, str]], skip: Tuple[str, ...] = ()) -> str:
    typed: Dict[str, str] = {}
    for point, direction, eq_class in rows:
        if any(eq_class.endswith(k) for k in skip):
            continue
        role = ROLE.get((direction.rsplit("#", 1)[-1], kind_of(eq_class)))
        if role:
            typed[point] = role
    lines = [
        "# Plant water-temperature points typed by the circuit they measure (BUG-1564).",
        "#",
        "# GENERATED by scripts/provision_plant_water_roles.py from the live graph: each point's",
        "# circuit follows from the equipment it is a point of (chiller -> chilled water; boiler or",
        "# heating heat pump -> hot water). Extra rdf:type triples only; nothing else is stated.",
        *(
            [f"# Equipment kinds deliberately left untyped in this run: {', '.join(skip)}."]
            if skip
            else []
        ),
        "",
        "@prefix rdf:   <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .",
        "@prefix brick: <https://brickschema.org/schema/Brick#> .",
    ]
    # The building's own prefix, read from the points (the swap validator checks it against the
    # declared namespace, so a file of full IRIs would be the one file it could not check).
    spaces = {pt.rsplit("#", 1)[0] for pt in typed if "#" in pt}
    ns = next(iter(spaces)) if len(spaces) == 1 else ""
    if ns:
        lines.append(f"@prefix bldg:  <{ns}#> .")
    lines.append("")
    for point in sorted(typed):
        name = f"bldg:{point.rsplit('#', 1)[1]}" if ns else f"<{point}>"
        lines.append(f"{name} rdf:type brick:{typed[point]} .")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--building", required=True)
    ap.add_argument("--endpoint", default="http://127.0.0.1:7200/repositories/bldg")
    ap.add_argument("--out", default="")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument(
        "--skip-kind",
        action="append",
        default=[],
        help="equipment class local name to leave untyped (repeatable), e.g. --skip-kind Boiler",
    )
    args = ap.parse_args()
    rows = fetch(args.endpoint)
    ttl = build_ttl(rows, tuple(args.skip_kind))
    n = sum(1 for line in ttl.splitlines() if " rdf:type brick:" in line)
    if args.dry_run:
        print(ttl)
        return 0
    out = Path(args.out) if args.out else Path("input") / f"{args.building}_plant_water_roles.ttl"
    out.write_text(ttl, encoding="utf-8")
    print(f"wrote {n} typed point(s) to {out}")
    return 0 if n else 1


if __name__ == "__main__":
    sys.exit(main())
