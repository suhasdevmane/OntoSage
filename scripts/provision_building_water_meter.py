#!/usr/bin/env python3
"""Give the building's main water meter an interval-volume series (CAVEAT-1562 follow-up).

"How much water did the building use yesterday?" could not be answered: the graph declares a
``brick:Building_Water_Meter`` with no timeseries, and the floor water points are flow channels
whose unit does not say what a total of them would mean. This gives the main meter what a real
utility meter reports -- the litres drawn in each 15-minute interval -- so a total is a sum, a
cost is that sum times the water tariff the registers already hold, and a trend is plain.

Two halves, both idempotent:

* ``--write-ttl`` writes ``input/<building>_building_water_meter.ttl``: the existing meter gains a
  ``ref:TimeseriesReference`` (``ref:storedAt bldg:water_data``) and ``qudt:hasUnit unit:L``.
* ``--backfill`` writes the history from ``--start`` to now, every 15 minutes, drawn by the SAME
  shape the live publisher uses (``sensor_signal.water_fraction``), so history and live agree.
  Existing rows for the meter are left alone; only missing intervals are written.

Synthetic, and said to be: the comment says so, and the store's nature is the registry's.

    python scripts/provision_building_water_meter.py --write-ttl --backfill --start 2026-06-01
    python scripts/strip_simulated_flag.py --dir input     # decision D1: no shipped record
                                                            # declares an origin
"""

from __future__ import annotations

import argparse
import random
import sys
import uuid as uuidlib
from datetime import datetime, timedelta
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "mysql-dummy-publish-dev"))

from sensor_signal import water_fraction  # noqa: E402

TABLE = "water_data"
STEP = timedelta(minutes=15)
HI_LITRES = 600.0


def _building() -> tuple:
    cfg = yaml.safe_load((REPO / "input" / "building.yaml").read_text(encoding="utf-8"))
    return cfg["building_id"], cfg["ontology_namespace"]


def meter_uuid(namespace: str) -> str:
    """A stable id for the meter's interval series."""
    return str(uuidlib.uuid5(uuidlib.NAMESPACE_URL, f"{namespace}Building_Water_Meter/interval"))


def ttl_text(namespace: str, uid: str) -> str:
    return f"""# The main water meter's interval-volume series (CAVEAT-1562 follow-up).
#
# GENERATED by scripts/provision_building_water_meter.py. The meter already exists in the graph;
# this adds its readings: litres drawn in each 15-minute interval, stored in water_data. The data
# is synthetic and drawn by the publisher's own shape (sensor_signal.water_fraction).

@prefix rdfs:     <http://www.w3.org/2000/01/rdf-schema#> .
@prefix brick:    <https://brickschema.org/schema/Brick#> .
@prefix ref:      <https://brickschema.org/schema/Brick/ref#> .
@prefix qudt:     <http://qudt.org/schema/qudt/> .
@prefix xsd:      <http://www.w3.org/2001/XMLSchema#> .
@prefix ontosage: <http://ontosage.org/capabilities#> .
@prefix bldg:     <{namespace}> .

bldg:Building_Water_Meter
    rdfs:comment "Volume of mains water drawn by the whole building in each 15-minute interval (litres). A total over a period is the sum of its intervals." ;
    qudt:hasUnit <http://qudt.org/vocab/unit/L> ;
    ontosage:isSimulated "true"^^xsd:boolean ;
    ref:hasExternalReference [
        a ref:TimeseriesReference ;
        ref:hasTimeseriesId "{uid}" ;
        ref:storedAt bldg:{TABLE}
    ] .
"""


def _connect():
    import pymysql

    env = {}
    for line in (REPO / ".env").read_text(encoding="utf-8").splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            env[k.strip()] = v.strip().strip('"').strip("'")
    host = env.get("MYSQL_HOST", "127.0.0.1")
    if host in ("mysql", "host.docker.internal"):
        host = "127.0.0.1"
    return pymysql.connect(
        host=host,
        port=int(env.get("MYSQL_PORT", "3306")),
        user=env.get("MYSQL_USER"),
        password=env.get("MYSQL_PASSWORD"),
        database=env.get("MYSQL_DATABASE", "sensordb"),
        init_command="SET time_zone='+00:00'",
        autocommit=False,
    )


def backfill(uid: str, start: datetime, end: datetime, seed: int = 20261011) -> int:
    """Write every missing 15-minute interval for the meter between start and end (UTC)."""
    conn = _connect()
    cur = conn.cursor()
    cur.execute(f"SHOW COLUMNS FROM `{TABLE}`")
    cols = [r[0] for r in cur.fetchall()]
    tcol = next(c for c in cols if c.lower() in ("datetime", "timestamp"))
    vcol = next(c for c in cols if c.lower() == "value")
    ucol = next(c for c in cols if c.lower() == "uuid")
    cur.execute(f"SELECT `{tcol}` FROM `{TABLE}` WHERE `{ucol}`=%s", (uid,))
    have = {r[0].replace(second=0, microsecond=0) for r in cur.fetchall()}
    rng = random.Random(seed)
    rows = []
    t = start.replace(second=0, microsecond=0, minute=(start.minute // 15) * 15)
    while t <= end:
        if t not in have:
            v = HI_LITRES * water_fraction(t) * (1.0 + rng.gauss(0, 0.08))
            rows.append(
                (uid, t.strftime("%Y-%m-%d %H:%M:%S"), round(max(0.0, min(HI_LITRES, v)), 1))
            )
        t += STEP
    for i in range(0, len(rows), 5000):
        cur.executemany(
            f"INSERT INTO `{TABLE}` (`{ucol}`, `{tcol}`, `{vcol}`) VALUES (%s, %s, %s)",
            rows[i : i + 5000],
        )
    conn.commit()
    conn.close()
    return len(rows)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--write-ttl", action="store_true")
    ap.add_argument("--backfill", action="store_true")
    ap.add_argument("--start", default="2026-06-01")
    # Stop before the live publisher's first row when filling a gap: its readings sit off the
    # quarter-hour grid, so a backfill run past them would add a second reading per interval.
    ap.add_argument("--end", default="", help="UTC end of the backfill (default: now)")
    args = ap.parse_args()
    building_id, namespace = _building()
    uid = meter_uuid(namespace)
    if args.write_ttl:
        out = REPO / "input" / f"{building_id}_building_water_meter.ttl"
        out.write_text(ttl_text(namespace, uid), encoding="utf-8")
        print(f"wrote {out.name} (series {uid})")
    if args.backfill:
        end = datetime.fromisoformat(args.end) if args.end else datetime.utcnow()
        n = backfill(uid, datetime.fromisoformat(args.start), end)
        print(f"backfilled {n} intervals into {TABLE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
