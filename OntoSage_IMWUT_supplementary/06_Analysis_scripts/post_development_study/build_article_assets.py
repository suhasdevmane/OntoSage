def width_of(pdf: Path) -> str:
    """Include each figure at its own width so every figure's text prints at the same size (7.5 pt): a half-width
    figure stretched to \\linewidth would print its text nearly twice as large."""
    try:
        import fitz  # PyMuPDF
        with fitz.open(pdf) as doc:
            w_in = doc[0].rect.width / 72
        frac = min(1.0, w_in / 5.48)          # acmsmall text width, as in fig_style.FULL
        return r"\linewidth" if frac > 0.97 else f"{frac:.2f}\\linewidth"
    except Exception:  # noqa: BLE001
        return r"\linewidth"


