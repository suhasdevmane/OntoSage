def labels_note(src: str) -> str:
    """Who produced a table's answer labels, in the words the Method uses (plan 19, Option A)."""
    if src == "HUMAN_AGREED":       # the reviewed proposals, with the sampled disagreements settled (G14)
        return ("Labels: the AI's proposals as reviewed by the first author, with the disagreements on the second "
                "coder's sample settled.")
    if src == "AUTHOR_CHECKED":
        return "PROVISIONAL: the first author's check of the AI pre-labels; agreement with a second coder pending."
    return "PROVISIONAL AI pre-labels (pass 1); replace before submission."


def tex(s) -> str:
    s = str(s)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("_", r"\_"), ("#", r"\#"), ("$", r"\$")):
        s = s.replace(a, b)
    return s


def pct(x, d=0) -> str:
    return f"{100 * x:.{d}f}"


def write_table(name: str, caption: str, label: str, colspec: str, header: list, rows: list, notes: str = "",
                provisional: bool = False) -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    with (GEN / f"{name}.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)
    out = [f"% {name}.tex — generated by build_article_assets.py; do not edit by hand (re-run the script).",
           "% DRAFT caption: rewrite in your own words; keep the numbers."]
    if provisional:
        out.append("% PROVISIONAL: rests on labels not yet settled with the second coder; re-run after settling (G14).")
    colspec = colspec.replace("p{", r">{\raggedright\arraybackslash}p{")   # wrapped cells: no hyphenation, ragged right
    out += [r"\begin{table}[t]", r"\centering", r"\small", rf"\caption{{{caption}}}", rf"\label{{{label}}}",
            rf"\begin{{tabular}}{{{colspec}}}", r"\toprule", " & ".join(tex(h) for h in header) + r" \\", r"\midrule"]
    for r in rows:
        cells = [(r"\quad " + tex(str(c).lstrip())) if str(c).startswith("   ") else tex(c) for c in r]
        out.append(" & ".join(cells) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}"]
    if notes:
        out.append(rf"\par\smallskip\parbox{{\linewidth}}{{\footnotesize {tex(notes)}}}")
    # the caption's and the note's own twin, so paper/verify_claims.py can trace their numbers as well as the cells
    (GEN / f"{name}_notes.txt").write_text(f"caption: {caption}\nnote: {notes}\n", encoding="utf-8")
    out.append(r"\end{table}")
    (GEN / f"{name}.tex").write_text("\n".join(out) + "\n", encoding="utf-8")


