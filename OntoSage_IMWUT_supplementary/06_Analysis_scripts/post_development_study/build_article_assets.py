def review(*mats: str) -> str:
    """What the first author's review of these materials has reached, from the checking tool's summary: the deviations
    table says 'reviewed' only once every item is checked and the export accepted the pace (methods match the record)."""
    p = LABELS / "author_check" / "check_summary.json"
    s = json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}
    e = [s.get(m) or {} for m in mats]
    checked, total = sum(x.get("checked", 0) for x in e), sum(x.get("total", 0) for x in e)
    if all(x and x.get("checked") == x.get("total") and x.get("exported") is not False for x in e):
        return "the first author reviewed each proposal and kept or changed it"
    return f"the first author's review of the proposals is in progress ({checked:,} of {total:,})"


