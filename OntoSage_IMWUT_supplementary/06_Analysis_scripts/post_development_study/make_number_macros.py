#!/usr/bin/env python3
"""Turn every number in results/results_numbers.csv into a LaTeX lookup, so the article never types a study number.

    python make_number_macros.py

Writes paper/generated/study_v9/numbers.tex. In the article:

    \\input{generated/study_v9/numbers.tex}     % in the preamble, after xcolor
    ... \\sv{E1_S1_k_n} ...                     % prints 7/30

A key that does not exist stops the build with an error (never a silent blank). A range "10.0-40.0" prints with an en
dash. Every number whose label source is not HUMAN_AGREED (AI pre-labels, or the author's check before agreement) is
drawn in orange while \\svdrafttrue is set (the default), and \\svprovisionalcount says how many there are; put
\\svdraftfalse before \\begin{document} for the submitted version. Numbers that rest on no labels (decisions against
the keys, timing, SUS) are final and never coloured.
"""

from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from study_paths import REPO, RESULTS  # noqa: E402

OUT = REPO / "paper" / "generated" / "study_v9" / "numbers.tex"
RANGE = re.compile(r"^(-?\d+(?:\.\d+)?)-(-?\d+(?:\.\d+)?)$")
SPECIAL = {"%": r"\%", "&": r"\&", "#": r"\#", "_": r"\_", "$": r"\$", "{": r"\{", "}": r"\}",
           "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
KEY_OK = re.compile(r"^[A-Za-z0-9_.+\-]+$")

HEAD = r"""% Generated by 11_Study_Materials/F_Analysis/make_number_macros.py from results/results_numbers.csv.
% Do not edit by hand: re-run the pipeline (run_pipeline.py) and this file is rewritten.
\makeatletter
\newif\ifsvdraft \svdrafttrue
\providecommand{\svprovcolor}{orange}
\newcommand{\svprov}[1]{\ifsvdraft\textcolor{\svprovcolor}{#1}\else#1\fi}
\newcommand{\sv}[1]{\ifcsname sv@#1\endcsname\csname sv@#1\endcsname\else
  \PackageError{studyvalues}{Unknown study value '\detokenize{#1}'}{Check the key in results_numbers.csv}%
  \textbf{??\detokenize{#1}??}\fi}
"""


def tex_value(v: str) -> str:
    v = v.strip()
    m = RANGE.match(v)
    if m:
        return f"{m.group(1)}--{m.group(2)}"
    return "".join(SPECIAL.get(ch, ch) for ch in v)


def main() -> int:
    rows = list(csv.DictReader((RESULTS / "results_numbers.csv").open(encoding="utf-8")))
    seen, lines, prov = set(), [HEAD], 0
    bad = [r["key"] for r in rows if not KEY_OK.match(r["key"])]
    if bad:
        raise SystemExit(f"keys LaTeX cannot carry: {bad[:5]}")
    for r in rows:
        k = r["key"]
        if k in seen:
            raise SystemExit(f"duplicate key {k}")
        seen.add(k)
        val = tex_value(r["value"])
        src = (r.get("label_source") or "").strip()
        # Final: the reviewed labels with the sample's disagreements settled; the review figures once the review is
        # complete; Stage 5, which has one coder by design, once the first author has reviewed it; agreement, settlement
        # and blinding figures, measured once against the second coder. Everything else may still move: orange.
        if src and src not in ("HUMAN_AGREED", "AUTHOR_CHECK_COMPLETE", "AUTHOR_CHECKED_SINGLE_CODER", "SECOND_CODER"):
            prov += 1
            val = r"\svprov{" + val + "}"
        lines.append(rf"\expandafter\def\csname sv@{k}\endcsname{{{val}}}% {src or 'final'}")
    lines.append(rf"\newcommand{{\svprovisionalcount}}{{{prov}}}")
    lines.append(r"\makeatother")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(seen)} numbers -> {OUT} ({prov} still rest on labels not yet agreed by two coders)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
