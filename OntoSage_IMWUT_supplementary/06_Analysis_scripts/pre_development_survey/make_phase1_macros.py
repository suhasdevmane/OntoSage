    rows = read_csv(p)
    for r in rows:
        lv = r["Level"]
        put(f"lvl{lv}_n{sfx}", r["n_observations"], p, f"level {lv}, n_observations")
        for k in range(1, 5):
            put(f"lvl{lv}_rank{k}{sfx}", dec(float(r[f"pct_rank{k}"]), 1), p, f"level {lv}, pct_rank{k}")
