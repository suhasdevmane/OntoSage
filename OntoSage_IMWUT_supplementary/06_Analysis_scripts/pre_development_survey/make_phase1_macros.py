def tex_escape(s: str) -> str:
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
           "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(rep.get(ch, ch) for ch in s)


def write_table(name: str, header: List[str], rows: List[List[str]], caption: str, note: str, label: str,
                colspec: str, tex_rows: List[str], outdir: str = "") -> None:
    outdir = outdir or OUT
    with io.open(os.path.join(outdir, name + ".csv"), "w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(header)
        w.writerows([[c.replace("{,}", ",").replace("$", "") for c in r] for r in rows])   # plain "1,904", "-0.25"
    with io.open(os.path.join(outdir, name + "_notes.txt"), "w", encoding="utf-8") as fh:
        fh.write(f"caption: {caption}\nnote: {note}\n")
    lines = [f"% {name}.tex -- generated by paper/scripts/make_phase1_macros.py; do not edit by hand.",
             r"\begin{table}[t]", r"\centering", r"\small", rf"\caption{{{caption}}}", rf"\label{{{label}}}",
             rf"\begin{{tabular}}{{{colspec}}}", r"\toprule",
             " & ".join(rf"\textbf{{{h}}}" for h in header) + r" \\", r"\midrule"]
    lines += tex_rows
    lines += [r"\bottomrule", r"\end{tabular}"]
    if note:
        lines.append(rf"\par\smallskip\parbox{{\linewidth}}{{\footnotesize {note}}}")
    lines.append(r"\end{table}")
    with io.open(os.path.join(outdir, name + ".tex"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


