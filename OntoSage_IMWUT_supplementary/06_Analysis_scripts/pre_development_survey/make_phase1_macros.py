def sample_questions_table() -> None:
    sel_p = os.path.join(PAPER, "generated", "sample-questions.csv")
    sel = read_csv(sel_p)
    corp = read_csv(os.path.join(SURVEY, "corpus", "classified_corpus.csv"))

    def norm(t: str) -> str:
        t = re.sub(r"\\[a-zA-Z]+\s*", " ", t.lower())
        return " ".join(re.sub(r"[^a-z0-9 ]", " ", t).split())

    by_pid = defaultdict(list)
    for r in corp:
        by_pid[r["PID"]].append(r)
    label = {"ENERGY": "Energy", "AIR_QUALITY": "Air quality", "THERMAL": "Thermal", "LIGHTING": "Lighting",
             "SAFETY": "Safety", "SECURITY": "Security", "OCCUPANCY": "Occupancy", "OTHER": "No domain matched"}
    cpx = {"LOOKUP": "Lkp", "AGGREGATION": "Agg", "MULTI_STEP": "Mlt"}
    out, tex_rows, prev = [], [], None
    for s in sel:
        cands = by_pid.get(s["pid"], [])
        target = norm(s["question"])
        best, score = None, 0.0
        for r in cands:
            sc = 1.0 if norm(r["Question"]) == target else difflib.SequenceMatcher(None, target,
                                                                                      norm(r["Question"])).ratio()
            if sc > score:
                best, score = r, sc
        if best is None or score < 0.8:
            raise SystemExit(f"sample question not found in the corpus for {s['pid']}: {s['question'][:40]}")
        text = best["Question"].strip()
        dom = label.get(best["domain_l1"], best["domain_l1"].replace("_", " ").title())
        out.append([best["PID"], dom, f"S{best['Stage']}", cpx[best["complexity"]], text, f"{score:.2f}"])
        cell = dom if dom != prev else ""
        prev = dom
        tex_rows.append(rf"{cell} & S{best['Stage']} & {cpx[best['complexity']]} & {tex_escape(text)} \\")
    caption = ("Sample questions from the corpus, printed exactly as contributors typed them. Domain and complexity "
               "are the automated classifier's labels (agreement with a second automated classifier in "
               r"Table~\ref{tab:irr}). Stage: S1 Open Minded, S2 Sensing \& Semantics, S3 Scenario-Based, S4 "
               "Goal-Oriented. Lkp, Agg, Mlt: LOOKUP, AGGREGATION, MULTI\\_STEP.")
    write_table("tab_sample_questions", ["Domain", "Stage", "Cpx.", "Question"],
                [[r[1], r[2], r[3], r[4]] for r in out], caption, "", "tab:sample-questions",
                r"@{}>{\raggedright\arraybackslash}p{2.1cm}p{0.8cm}p{0.7cm}>{\raggedright\arraybackslash}p{9.1cm}@{}",
                tex_rows)
    with io.open(os.path.join(OUT, "tab_sample_questions_match.csv"), "w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["pid", "domain", "stage", "complexity", "corpus_text", "match_to_earlier_draft_text"])
        w.writerows(out)
    put("sample_n", str(len(out)), sel_p, "rows of the authored selection")
    put("sample_edited", str(sum(1 for r in out if r[5] != "1.00")), sel_p,
        "selected questions whose earlier-draft wording differed from the corpus text")


