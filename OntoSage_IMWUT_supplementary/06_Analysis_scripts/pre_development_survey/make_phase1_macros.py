# The de-duplicator's canonical form (mirrors scripts/clean_duplicate_questions.py, canonical()).
_TRAIL = re.compile(r"[\s?!.,;:]+$")
_LWRAP = re.compile(r"^[\s\"'`(\[]+")
_RWRAP = re.compile(r"[\s\"'`)\]]+$")


def canonical(q: str) -> str:
    q = unicodedata.normalize("NFKC", q or "").strip().lower()
    q = _LWRAP.sub("", q)
    q = _RWRAP.sub("", q)
    q = re.sub(r"\s+", " ", q)
    return _TRAIL.sub("", q).strip()


